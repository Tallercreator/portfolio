import { existsSync } from 'node:fs';
import { join } from 'node:path';

/*
  Ссылка на резюме появляется в интерфейсе только когда файл действительно
  лежит в public. Так на сайте не бывает битой ссылки, а положить резюме
  можно в любой момент — пересборка подхватит.

  Проверка живёт отдельным модулем не случайно: в About есть локальная
  переменная `process` со списком шагов работы, и она перекрыла бы
  глобальный process.cwd() внутри самого компонента.
*/
export const hasCv = existsSync(join(process.cwd(), 'public/cv.pdf'));
